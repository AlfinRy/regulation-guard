/**
 * Export utilities for compliance reports.
 *
 * Generates downloadable Markdown and PDF files from the report data.
 */

import type { ReviewResult, ReportFinding } from './api';

// ---------------------------------------------------------------------------
// Markdown Export
// ---------------------------------------------------------------------------

/**
 * Generate a Markdown string from a compliance report.
 */
export function generateMarkdown(
  result: ReviewResult,
  fileName: string,
): string {
  const { report } = result;
  const date = new Date().toLocaleDateString('en-GB', {
    day: '2-digit',
    month: 'long',
    year: 'numeric',
  });

  const lines: string[] = [];

  // Header
  lines.push('# Compliance Review Report');
  lines.push('');
  lines.push(`**Document:** ${fileName}`);
  lines.push(`**Regulations:** ${result.regulations.map(r => r.toUpperCase()).join(', ')}`);
  lines.push(`**Generated:** ${date}`);
  lines.push(`**Session:** ${result.sessionId}`);
  lines.push('');

  // Executive Summary
  lines.push('---');
  lines.push('');
  lines.push('## Executive Summary');
  lines.push('');
  lines.push(`**Overall Risk:** ${report.overallRisk}`);
  lines.push(`**Critical Violations:** ${report.criticalCount}`);
  lines.push(`**Warnings:** ${report.warningCount}`);
  lines.push(`**Passing Clauses:** ${report.passingCount}`);
  lines.push('');
  lines.push(report.summary);
  lines.push('');

  // Recommendation
  lines.push('### Recommendation');
  lines.push('');
  lines.push(`> ${report.recommendation}`);
  lines.push('');

  // Risk Matrix Table
  lines.push('---');
  lines.push('');
  lines.push('## Risk Matrix');
  lines.push('');
  lines.push('| Clause | Category | Severity | Regulation | Status | Confidence | Escalate |');
  lines.push('|--------|----------|----------|------------|--------|------------|----------|');

  for (const f of report.findings) {
    lines.push(
      `| ${f.id} | ${f.category} | ${f.severity} | ${f.regulation} ${f.article} | ${f.status} | ${f.confidence}% | ${f.humanReview ? '⚠️ YES' : '✅ No'} |`,
    );
  }
  lines.push('');

  // Detailed Findings
  lines.push('---');
  lines.push('');
  lines.push('## Detailed Findings');
  lines.push('');

  for (const f of report.findings) {
    lines.push(`### ${f.id} — ${f.category} [${f.severity}]`);
    lines.push('');
    lines.push(`**Status:** ${f.status}`);
    lines.push(`**Regulation:** ${f.regulation} — ${f.article}`);
    lines.push(`**Confidence:** ${f.confidence}%`);
    if (f.humanReview) {
      lines.push(`**⚠️ FLAGGED FOR HUMAN REVIEW**`);
    }
    lines.push('');
    lines.push('**Clause Text:**');
    lines.push(`> ${f.clauseText}`);
    lines.push('');
    lines.push('**Reasoning:**');
    lines.push(f.reasoning);
    lines.push('');
  }

  // Regulatory References
  lines.push('---');
  lines.push('');
  lines.push('## Regulatory References');
  lines.push('');

  const regCitations = report.findings.reduce<Record<string, string[]>>((acc, f) => {
    const reg = f.regulation;
    if (!acc[reg]) acc[reg] = [];
    const cite = f.article !== 'N/A' ? f.article : '';
    if (cite && !acc[reg].includes(cite)) acc[reg].push(cite);
    return acc;
  }, {});

  for (const [reg, articles] of Object.entries(regCitations)) {
    lines.push(`**${reg}**`);
    for (const art of articles) {
      lines.push(`- ${art}`);
    }
    lines.push('');
  }

  // Footer
  lines.push('---');
  lines.push('');
  lines.push('*Generated by RegulationGuard — Multi-Agent Compliance & Regulatory Review System*');

  return lines.join('\n');
}

/**
 * Trigger a Markdown file download in the browser.
 */
export function downloadMarkdown(result: ReviewResult, fileName: string): void {
  const md = generateMarkdown(result, fileName);
  const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
  triggerDownload(blob, `${fileName.replace(/\.[^.]+$/, '')}_compliance_report.md`);
}

